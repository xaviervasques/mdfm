# ---------------------------------------------------------------- subject-mean model

def z_factor(n, alpha, power):
    return (stats.norm.ppf(1 - alpha / 2) + stats.norm.ppf(power)) / math.sqrt(n)


def t_factor(n, alpha, power):
    """delta / sigma at which a one-sample t interval excludes 0 from below with the given power."""
    df = n - 1
    tc = stats.t.ppf(1 - alpha / 2, df)

    def f(d):
        return stats.nct.sf(tc, df, d * math.sqrt(n)) - power

    hi = 1.0
    while f(hi) < 0:
        hi *= 2
    return optimize.brentq(f, 0.0, hi, xtol=1e-10)


def multisets(n):
    """All bootstrap count vectors of n units drawn n times, with multinomial weights."""
    counts = []
    for comb in itertools.combinations_with_replacement(range(n), n):
        counts.append(np.bincount(comb, minlength=n))
    c = np.array(counts, dtype=np.int64)
    logw = (special.gammaln(n + 1) - special.gammaln(c + 1).sum(axis=1) - n * math.log(n))
    w = np.exp(logw)
    return c, w / w.sum()


def order_stat_index(p, b):
    """0-based index of the type-1 (inverted cdf) quantile p among b sorted values."""
    return max(0, min(b - 1, int(math.ceil(p * b - 1e-9)) - 1))


def weighted_type1(sorted_vals, sorted_w_cum, p):
    """Type-1 quantile per column: first value whose cumulative weight reaches p."""
    idx = (sorted_w_cum < p - 1e-12).sum(axis=0)
    idx = np.minimum(idx, sorted_vals.shape[0] - 1)
    return np.take_along_axis(sorted_vals, idx[None, :], axis=0)[0]


def boot_bounds_mean(n, alpha, sims, boot, rng, chunk=500):
    """Percentile-bootstrap lower and upper bounds of a mean of n N(0, 1) units, per simulation.

    Enumerates the C(2n - 1, n) resamples with their weights when there are at most `boot` of
    them (NR-1.5 draft proposal); otherwise draws `boot` resamples per chunk of simulations
    (the simulations of one chunk share that draw, which only correlates their Monte Carlo error).
    """
    n_multi = math.comb(2 * n - 1, n)
    enumerated = n_multi <= boot
    lo = np.empty(sims)
    hi = np.empty(sims)
    if enumerated:
        c, w = multisets(n)
        cf = c.astype(float) / n
    for s0 in range(0, sims, chunk):
        s1 = min(sims, s0 + chunk)
        x = rng.standard_normal((n, s1 - s0))
        if enumerated:
            means = cf @ x                       # (M, s)
            order = np.argsort(means, axis=0, kind="stable")
            sv = np.take_along_axis(means, order, axis=0)
            wc = np.cumsum(w[order], axis=0)
            lo[s0:s1] = weighted_type1(sv, wc, alpha / 2)
            hi[s0:s1] = weighted_type1(sv, wc, 1 - alpha / 2)
        else:
            cnt = rng.multinomial(n, np.full(n, 1.0 / n), size=boot).astype(float) / n
            means = cnt @ x                      # (boot, s)
            kl = order_stat_index(alpha / 2, boot)
            ku = order_stat_index(1 - alpha / 2, boot)
            part = np.partition(means, (kl, ku), axis=0)
            lo[s0:s1] = part[kl]
            hi[s0:s1] = part[ku]
    return lo, hi, enumerated, (n_multi if enumerated else boot)


def cluster_factors(n, alpha, powers, sims, boot, seed):
    """Rows of k_n (MDD over sigma_d at margin 0) per method and power, with the bootstrap's
    false-pass rate at delta = 0 and its absent factor a_n."""
    rng = np.random.default_rng([seed, n])
    lo, hi, enumerated, resamples = boot_bounds_mean(n, alpha, sims, boot, rng)
    false_pass = float(np.mean(lo > 0))
    rows = []
    for p in powers:
        kz = z_factor(n, alpha, p)
        kt = t_factor(n, alpha, p) if n >= 2 else float("nan")
        kb = float(-np.quantile(lo, 1 - p))
        ab = float(np.quantile(hi, p))
        for method, k, a, fp in (("z", kz, kz, alpha / 2), ("t", kt, kt, alpha / 2),
                                 ("boot", kb, ab, false_pass)):
            rows.append({"n": n, "method": method, "power": p, "k": k, "absent_factor": a,
                         "false_pass_at_0": fp,
                         "resampling": ("enumerated" if enumerated else "drawn") if method == "boot" else "",
                         "resamples": resamples if method == "boot" else "",
                         "sims": sims if method == "boot" else ""})
    return rows


# ---------------------------------------------------------------- paired AUROC

class AurocSim:
    """Paired AUROC difference under a binormal model with common random numbers."""

    def __init__(self, n_pos, n_neg, rho, sims, boot, alpha, seed, chunk=100):
        self.n_pos, self.n_neg, self.rho = n_pos, n_neg, rho
        self.sims, self.boot, self.alpha, self.chunk = sims, boot, alpha, chunk
        rng = np.random.default_rng([seed, n_pos, n_neg, int(round(rho * 1000))])
        n = n_pos + n_neg
        e0 = rng.standard_normal((sims, n))
        eta = rng.standard_normal((sims, n))
        self.e0 = e0
        self.e1 = rho * e0 + math.sqrt(max(0.0, 1 - rho * rho)) * eta
        self.boot_seed = int(rng.integers(0, 2**31 - 1))
        self._cache = {}

    @staticmethod
    def pair_matrix(scores, n_pos):
        pos = scores[:, :n_pos, None]
        neg = scores[:, None, n_pos:]
        return (pos > neg).astype(float) + 0.5 * (pos == neg)

    def auc_matrices(self, a0, delta):
        mu0 = math.sqrt(2) * stats.norm.ppf(a0)
        mu1 = math.sqrt(2) * stats.norm.ppf(a0 + delta)
        s0 = self.e0.copy()
        s0[:, :self.n_pos] += mu0
        s1 = self.e1.copy()
        s1[:, :self.n_pos] += mu1
        return self.pair_matrix(s0, self.n_pos), self.pair_matrix(s1, self.n_pos)

    def run(self, a0, delta, margin=0.0):
        """(power, observed differences, lower bounds) at one delta."""
        key = (a0, round(delta, 12), margin)
        if key in self._cache:
            return self._cache[key]
        h0, h1 = self.auc_matrices(a0, delta)
        d = h1 - h0
        diff = d.mean(axis=(1, 2))
        lo = np.empty(self.sims)
        rng = np.random.default_rng(self.boot_seed)   # same resamples for every delta
        kl = order_stat_index(self.alpha / 2, self.boot)
        npn = self.n_pos * self.n_neg
        for s0 in range(0, self.sims, self.chunk):
            s1 = min(self.sims, s0 + self.chunk)
            cp = rng.multinomial(self.n_pos, np.full(self.n_pos, 1.0 / self.n_pos), size=self.boot).astype(float)
            cn = rng.multinomial(self.n_neg, np.full(self.n_neg, 1.0 / self.n_neg), size=self.boot).astype(float)
            t = np.matmul(cp[None, :, :], d[s0:s1])          # (s, boot, n_neg)
            bd = (t * cn[None, :, :]).sum(axis=2) / npn     # (s, boot)
            lo[s0:s1] = np.partition(bd, kl, axis=1)[:, kl]
        power = float(np.mean(lo > margin))
        out = (power, diff, lo)
        self._cache[key] = out
        return out

    def mdd(self, a0, power, margin=0.0, steps=10):
        """Smallest delta with simulated power >= target, by bisection; None if unattainable."""
        hi = (1.0 - a0) - 1e-6
        if self.run(a0, hi, margin)[0] < power:
            return None, self.run(a0, hi, margin)[0]
        lo = 0.0
        if self.run(a0, lo, margin)[0] >= power:
            return 0.0, self.run(a0, hi, margin)[0]
        for _ in range(steps):
            mid = 0.5 * (lo + hi)
            if self.run(a0, mid, margin)[0] >= power:
                hi = mid
            else:
                lo = mid
        return hi, self.run(a0, (1.0 - a0) - 1e-6, margin)[0]


def auroc_table(n_pos, n_neg, alpha, powers, sims, boot, seed, a0s=AUC_A0, rhos=AUC_RHO, steps=10):
    rows = []
    zc = stats.norm.ppf(1 - alpha / 2)
    for rho in rhos:
        sim = AurocSim(n_pos, n_neg, rho, sims, boot, alpha, seed)
        for a0 in a0s:
            p0, diff0, _ = sim.run(a0, 0.0, G16_MARGIN)
            se0 = float(np.std(diff0, ddof=1))
            for p in powers:
                m, p_max = sim.mdd(a0, p, G16_MARGIN, steps=steps)
                bloom = (zc + stats.norm.ppf(p)) * se0
                rows.append({
                    "a0": a0, "rho": rho, "power": p, "n_pos": n_pos, "n_neg": n_neg,
                    "se0": se0, "mdd_bloom": bloom,
                    "bloom_attainable": "yes" if a0 + bloom < 1.0 else "no",
                    "mdd_rule": "" if m is None else m,
                    "rule_attainable": "no" if m is None else "yes",
                    "false_pass_rule": p0, "power_at_auc_1": p_max,
                    "sims": sims, "boot": boot,
                })
    return rows


def auroc_ceiling(n_pos, n_neg, alpha, sims, boot, seed, a0s=AUC_A0, rhos=AUC_RHO):
    """Power of the G16 pass clause when the encoder AUROC is 1, on draws independent of auroc_table.

    At AUROC 1 every resample of the encoder separates the groups, so the decision depends on the
    baseline's scores alone and the ceiling does not depend on rho: the rho cells are independent
    estimates of one value per A0, and the pooled estimate is written beside them.
    """
    rows = []
    for rho in rhos:
        sim = AurocSim(n_pos, n_neg, rho, sims, boot, alpha, seed + 1)
        for a0 in a0s:
            p = sim.run(a0, (1.0 - a0) - 1e-6, G16_MARGIN)[0]
            rows.append({"a0": a0, "rho": rho, "scope": "cell", "sims": sims, "boot": boot,
                         "power_at_auc_1": p, "mc_se": math.sqrt(max(p * (1 - p), 1e-12) / sims)})
    for a0 in a0s:
        cells = [r for r in rows if r["a0"] == a0 and r["scope"] == "cell"]
        tot = sum(r["sims"] for r in cells)
        p = sum(r["power_at_auc_1"] * r["sims"] for r in cells) / tot
        rows.append({"a0": a0, "rho": "pooled", "scope": "pooled over rho", "sims": tot, "boot": boot,
                     "power_at_auc_1": p, "mc_se": math.sqrt(max(p * (1 - p), 1e-12) / tot)})
    return rows


def ceiling_verdict(ceiling, se, target, mult=CEILING_SE_MULT):
    """'yes' when the ceiling clears the target by mult SE, 'no' when it falls short by mult SE,
    'borderline' otherwise."""
    if ceiling - mult * se >= target:
        return "yes"
    if ceiling + mult * se < target:
        return "no"
    return "borderline"


