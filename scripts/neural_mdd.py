def parse_args(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tree", default=TREE)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--alpha", type=float, default=ALPHA)
    ap.add_argument("--sims", type=int, default=10000, help="simulations per n, subject-mean model")
    ap.add_argument("--boot", type=int, default=2000, help="bootstrap resamples (enumeration threshold too)")
    ap.add_argument("--auc-sims", type=int, default=2000)
    ap.add_argument("--auc-boot", type=int, default=1000)
    ap.add_argument("--auc-ceiling-sims", type=int, default=20000,
                    help="simulations per cell of the AUROC-1 ceiling check (independent draws)")
    ap.add_argument("--steps", type=int, default=10, help="bisection steps of the AUROC MDD")
    ap.add_argument("--a0", type=float, nargs="+", default=list(AUC_A0))
    ap.add_argument("--rho", type=float, nargs="+", default=list(AUC_RHO))
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--quick", action="store_true", help="small simulation sizes (tests)")
    args = ap.parse_args(argv)
    if args.quick:
        args.sims, args.boot, args.auc_sims, args.auc_boot, args.steps = 400, 200, 80, 100, 5
        args.auc_ceiling_sims = 200
    return args


def main(argv=None):
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    args = parse_args(argv)
    args.priority = below_normal()
    prov = build(args)
    print(f"wrote {args.out} in {prov['elapsed_s']} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
