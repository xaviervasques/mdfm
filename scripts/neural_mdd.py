# ---------------------------------------------------------------- guards and reading

class LockboxValueRefused(RuntimeError):
    """Raised when a path would expose lockbox persons' values."""


def guard_path(path):
    """Refuse any file that lists lockbox persons (sizes only, never a lockbox value)."""
    base = os.path.basename(str(path)).lower()
    if base.startswith("lockbox_persons"):
        raise LockboxValueRefused(f"refused: {path} lists lockbox persons; this script reads sizes only")
    return path


def read_text(path):
    guard_path(path)
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def read_csv(path):
    guard_path(path)
    with open(path, "r", encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def sha256_file(path):
    guard_path(path)
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def below_normal():
    """BelowNormal priority for this process (Windows); returns what was done."""
    try:
        import psutil
        p = psutil.Process()
        if os.name == "nt":
            p.nice(psutil.BELOW_NORMAL_PRIORITY_CLASS)
            return "BelowNormal"
        p.nice(10)
        return "nice 10"
    except Exception as e:  # noqa: BLE001
        return f"unchanged ({type(e).__name__})"


def wait_while_slow(path=SLOW, poll_s=60.0):
    t0 = time.time()
    told = False
    while os.path.exists(path):
        if not told:
            print(f"paused: {path} exists", flush=True)
            told = True
        time.sleep(poll_s)
    return time.time() - t0


