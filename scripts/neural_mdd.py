def fmt(x, nd=3):
    if x is None or x == "":
        return ""
    if isinstance(x, str):
        return x
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    return f"{x:.{nd}f}"


def write_csv(path, rows, fields):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: (fmt(r.get(k), 6) if isinstance(r.get(k), float) else r.get(k, "")) for k in fields})


