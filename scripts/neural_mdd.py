def parse_groups(text, total):
    """'Control 10, PD 20' -> {'Control': 10, 'PD': 20}; 'all 7' -> {'all': 7}.

    Returns None for a cell that lists names without counts (amass: 'subsets ACCAD, GRAB, ...');
    raises when the counts are readable but do not sum to the lockbox size.
    """
    out = {}
    for part in [p.strip() for p in text.split(",") if p.strip()]:
        m = re.match(r"^(.*\S)\s+(\d+)$", part)
        if not m:
            return None
        out[m.group(1)] = int(m.group(2))
    if sum(out.values()) != total:
        raise ValueError(f"groups {text!r} do not sum to {total}")
    return out


def parse_lockbox_summary(text):
    """The '## Lockbox' table of reports/lockbox/summary.md, plus the stated file SHA-256."""
    lines = text.splitlines()
    try:
        start = next(i for i, l in enumerate(lines) if l.strip() == "## Lockbox")
    except StopIteration as e:
        raise ValueError("no '## Lockbox' section") from e
    head = None
    rows = {}
    for l in lines[start + 1:]:
        s = l.strip()
        if s.startswith("## "):
            break
        if not s.startswith("|"):
            if head is not None and rows:
                break
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if head is None:
            head = [c.lower() for c in cells]
            continue
        if set("".join(cells)) <= set("-: "):
            continue
        r = dict(zip(head, cells))
        n_lb = int(r["lockbox persons"])
        rows[r["source"]] = {
            "lane": r["lane"],
            "pool_persons": int(r["pool persons"]),
            "lockbox_persons": n_lb,
            "groups": parse_groups(r["groups"], n_lb),
        }
    need = {"source", "lane", "pool persons", "lockbox persons", "groups"}
    if head is None or not need <= set(head):
        raise ValueError(f"lockbox table header not found or incomplete: {head}")
    m = re.search(r"Lockbox file SHA-256:\s*([0-9a-f]{64})", text)
    return rows, (m.group(1) if m else None)


def tiers_persons(rows, modality="eeg"):
    """{source: (persons, lockbox_persons)} for one modality of tiers_by_source.csv."""
    out = {}
    for r in rows:
        if r["modality"] != modality:
            continue
        val = (int(r["persons"]), int(r["lockbox_persons"]))
        if r["source"] in out and out[r["source"]] != val:
            raise ValueError(f"conflicting rows for {r['source']} {modality}")
        out[r["source"]] = val
    return out


def task_class(task):
    t = task.lower()
    for c in ("hold", "move", "rest"):
        if t.startswith(c):
            return c
    return t


def ds004998_units(admitted_rows, census_rows, reading):
    """Subjects that can enter the G21 medication line under one reading of OPEN-43.

    A subject enters when, for at least one task key (the class hold, move or rest, or the
    side-specific label), it has an admitted MedOff and an admitted MedOn recording. The pooled
    count leaves out the interleaved subjects of NR-6.4.6.
    """
    if reading not in ("class", "side"):
        raise ValueError(reading)
    by_sub = defaultdict(lambda: defaultdict(set))
    for r in admitted_rows:
        if r.get("g15_header_verdict", "pass") != "pass":
            continue
        key = task_class(r["task"]) if reading == "class" else r["task"]
        by_sub[r["sub"]][key].add(r["acq"])
    both = sorted(s for s, d in by_sub.items() if any({"MedOff", "MedOn"} <= v for v in d.values()))
    inter = sorted(r["sub"] for r in census_rows if r.get("interleaved") == "yes")
    pooled = [s for s in both if s not in inter]
    return {
        "reading": reading,
        "subjects_with_recordings": len(by_sub),
        "subjects_both_states": len(both),
        "interleaved": inter,
        "interleaved_in_both": [s for s in both if s in inter],
        "pooled": len(pooled),
    }


def order_null_feasible(feas_rows, unit="acquisitions", column="feasible"):
    """{reading: (subjects with a feasible task-matched order null, subjects)} at one unit of count.

    column 'feasible' needs distinct acquisition times; 'feasible_counting_ties' counts ties.
    """
    out = defaultdict(int)
    total = defaultdict(int)
    for r in feas_rows:
        if r["unit"] != unit:
            continue
        total[r["reading"]] += 1
        if r[column] == "yes":
            out[r["reading"]] += 1
    return {k: (out[k], total[k]) for k in sorted(total)}


